import type { Line, StoryBeat } from './story';

const COLOR = {
  RYE: '#facc15', JUNE: '#f472b6', SEVEN: '#5eead4', MAYA: '#93c5fd',
  SILAS: '#fb923c', VOSS: '#f87171', IMOGEN: '#c084fc', CHOIR: '#22d3ee',
} as const;
type Speaker = keyof typeof COLOR;
type Exchange = [Speaker, string];

function beat(nodeId: string, chapter: string, title: string, exchange: Exchange[], rewardGold = 45): StoryBeat {
  return {
    nodeId,
    chapter,
    title,
    lines: exchange.map(([who, text]): Line => ({ who, color: COLOR[who], text })),
    rewardGold,
  };
}

